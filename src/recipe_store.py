"""
Recipe identity and persistence: every recipe Cook-It can cook has a UUID,
and that UUID is its shareable address -- https://<host>/r/<uuid> (see the
frontend's Recipe page and api.py's /api/recipes/{uuid} endpoints).

THE BROWSER OWNS THE LIBRARY. Your recipes live in the browser
(IndexedDB, see frontend/src/lib/recipeStore.ts) and sync with Google Drive;
they are deliberately NOT committed to this repository. What lives here is a
MIRROR the browser uploads (recipes_library/, gitignored), because two things
can only be done server-side: matching free speech against your recipes
("dame la receta de tortilla") and resolving a /r/<uuid> link for someone
else's device.

Three kinds of recipes live here, and the difference matters:

  - SEED (recipes/*.json, git-tracked): the factory examples that ship with
    the project, `verified_source` True -- used AS-IS, never re-generated by
    the LLM. A fresh browser copies these into its library on first run and
    then owns its copy; edit them there or in Drive, not here.

  - LIBRARY (recipes_library/*.json, gitignored): the mirror of what the
    browser holds. Written by the browser, never by hand.
  - GENERATED (recipes_shared/<uuid>.json, gitignored runtime state): what
    the LLM produced for a request with no curated match, or what the
    pantry flow negotiated. `verified_source` False. These are persisted
    for exactly one reason: a URL that stops resolving the moment the
    session ends is not a shareable URL.

Generated recipes are keyed by their name's slug, so asking twice for the
same dish reuses the same UUID (and the same link) instead of piling up a
new file per request. This is a different cache from recipe_engine's
cache_llm/, which is keyed by what the USER SAID and exists to skip the LLM
call -- this one is keyed by the DISH and exists to give it an address.
"""
import json
import re
import uuid as uuid_lib
from pathlib import Path

BASE_DIR = Path(__file__).parent
RECIPES_DIR = BASE_DIR / "recipes"
SHARED_DIR = BASE_DIR / "recipes_shared"
SHARED_DIR.mkdir(exist_ok=True)
# The browser's library, mirrored here so speech matching and shared links
# can work. Gitignored: these are the user's recipes, not the project's.
LIBRARY_DIR = BASE_DIR / "recipes_library"
LIBRARY_DIR.mkdir(exist_ok=True)

# The fields that make up a shareable recipe, in the shape both the API and
# the cooking session expect. Anything else in a curated JSON file (e.g.
# its legacy "id" slug) stays in the file and is left out of the payload.
_RECIPE_FIELDS = ("uuid", "name", "servings", "summary", "ingredients", "steps", "tip")


def slugify(text):
    return re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")


def _new_uuid():
    return str(uuid_lib.uuid4())


def _backfill_uuid(path, recipe):
    """Curated recipes are hand-written, so a new one arrives without a UUID.
    It gets one the first time it's loaded, written back into its own file --
    generating a fresh one per process would hand out links that break on the
    next restart.

    Written in as text rather than re-dumping the parsed recipe: these files
    are hand-formatted (compact one-line ingredients in some, expanded in
    others) and adding an id has no business reflowing the whole file.
    """
    if recipe.get("uuid"):
        return recipe

    recipe["uuid"] = _new_uuid()
    raw = path.read_text()
    brace = raw.find("{")
    if brace == -1:  # not an object at all -- shouldn't happen, but don't corrupt it
        raw = json.dumps(recipe, ensure_ascii=False, indent=2) + "\n"
    else:
        raw = f'{raw[:brace + 1]}\n  "uuid": "{recipe["uuid"]}",{raw[brace + 1:]}'
    path.write_text(raw)
    return recipe


def load_curated():
    """The curated recipes, keyed by name (the key the picker and the
    speech-matching in recipe_engine both work with)."""
    recipes = {}
    for f in sorted(RECIPES_DIR.glob("*.json")):
        recipe = _backfill_uuid(f, json.loads(f.read_text()))
        recipe["verified_source"] = True
        recipes[recipe["name"]] = recipe
    return recipes


def load_shared():
    """Every generated recipe that has been given an address (unordered --
    the filename is the uuid, which sorts by nothing meaningful)."""
    recipes = []
    for f in sorted(SHARED_DIR.glob("*.json")):
        recipe = json.loads(f.read_text())
        recipe["verified_source"] = False
        recipes.append(recipe)
    return recipes


def load_library():
    """What the browser has told us it holds. Unordered."""
    recipes = []
    for f in sorted(LIBRARY_DIR.glob("*.json")):
        try:
            recipes.append(json.loads(f.read_text()))
        except json.JSONDecodeError:
            continue  # a half-written mirror file is not worth a 500
    return recipes


def save_library(recipes):
    """Replaces the mirror with what the browser just sent.

    A full replace rather than a merge, on purpose: the browser is the owner,
    so a recipe it no longer has should stop being cookable here too. Written
    to temporary files first and swapped in, so a browser that disconnects
    mid-upload can't leave the mirror half-empty.
    """
    written = set()
    for recipe in recipes:
        recipe_uuid = recipe.get("uuid")
        if not recipe_uuid:
            continue
        path = LIBRARY_DIR / f"{recipe_uuid}.json"
        tmp = path.with_suffix(".json.tmp")
        tmp.write_text(json.dumps(recipe, ensure_ascii=False, indent=2) + "\n")
        tmp.replace(path)
        written.add(path.name)
    for stale in LIBRARY_DIR.glob("*.json"):
        if stale.name not in written:
            stale.unlink()
    return len(written)


def library_recipe(recipe):
    """A mirrored recipe, flagged the way the rest of the app expects."""
    recipe = dict(recipe)
    recipe.setdefault("verified_source", False)
    return recipe


def find(recipe_uuid):
    """The recipe behind a shared link, curated or generated, or None if that
    UUID doesn't exist here (a stale link, or one from another install --
    UUIDs are per-machine, this app has no central registry)."""
    if not recipe_uuid:
        return None
    # The browser's copy wins: it may have edits the seed file doesn't.
    path = LIBRARY_DIR / f"{recipe_uuid}.json"
    if path.exists():
        return library_recipe(json.loads(path.read_text()))
    for recipe in load_curated().values():
        if recipe.get("uuid") == recipe_uuid:
            return recipe
    path = SHARED_DIR / f"{recipe_uuid}.json"
    if path.exists():
        recipe = json.loads(path.read_text())
        recipe["verified_source"] = False
        return recipe
    return None


def _find_shared_by_name(name):
    slug = slugify(name)
    if not slug:
        return None
    for recipe in load_shared():
        if slugify(recipe.get("name")) == slug:
            return recipe
    return None


def remember_generated(recipe):
    """Gives a generated recipe (LLM or pantry flow) a permanent address and
    stores it there. Returns the stored recipe, UUID included.

    Re-generating a dish that already has one keeps that UUID and overwrites
    the content: a link already sent to someone should show the current
    version of that dish rather than 404 or fork into a second URL.

    A recipe that ARRIVES with a uuid keeps it. That's how a recipe edited
    somewhere else and brought back -- Drive, see drive.pull() -- stays the
    same recipe instead of forking into a second address on every sync."""
    existing = _find_shared_by_name(recipe.get("name"))
    stored = {
        "uuid": recipe.get("uuid") or (existing or {}).get("uuid") or _new_uuid(),
        "name": recipe.get("name", ""),
        "servings": recipe.get("servings"),
        "summary": recipe.get("summary", ""),
        "ingredients": recipe.get("ingredients", []),
        "steps": recipe.get("steps", []),
        "tip": recipe.get("tip", ""),
    }
    (SHARED_DIR / f"{stored['uuid']}.json").write_text(
        json.dumps(stored, ensure_ascii=False, indent=2) + "\n"
    )
    stored["verified_source"] = False
    return stored


def public_recipe(recipe):
    """A recipe as the API hands it out: the shareable fields plus the
    verified_source flag, without any file-local extras."""
    return {
        **{k: recipe.get(k) for k in _RECIPE_FIELDS},
        "verified_source": bool(recipe.get("verified_source")),
    }
